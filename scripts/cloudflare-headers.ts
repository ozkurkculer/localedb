/**
 * Writes `.open-next/assets/_headers` for Cloudflare Workers static assets.
 *
 *   pnpm cf:build      (runs this after `opennextjs-cloudflare build`)
 *
 * On Workers, files in `.open-next/assets` (public/, _next/static) are served before the Worker
 * runs, so next.config `headers()` never reaches them (e.g. `X-Robots-Tag: noindex` on /_data).
 * This translates those rules into the `_headers` format, keeping next.config the single source,
 * plus the one header `next start` adds by itself: immutable caching of /_next/static.
 *
 * For the same reason a redirect whose source is a static file would never run; that fails here
 * (checked for sources without params).
 * Rules this script cannot translate exactly (`has`, `missing`, regex params, params in values)
 * fail too, rather than being dropped.
 */
import { existsSync } from 'fs';
import { writeFile } from 'fs/promises';
import path from 'path';
import { PHASE_PRODUCTION_SERVER } from 'next/constants';
import loadNextConfig from '../next.config';

const ASSETS = path.join(process.cwd(), '.open-next', 'assets');

/** What `next start` sends for the content-hashed files in /_next/static. */
const NEXT_STATIC = { source: '/_next/static/*', headers: [{ key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }] };

interface HeaderRule {
    source: string;
    headers: { key: string; value: string }[];
    has?: unknown;
    missing?: unknown;
}

/** `/a/b/:rest*` → `/a/b/*`. Only literal segments and a trailing catch-all are supported. */
function toAssetPattern(source: string): string {
    const pattern = source.replace(/\/:[A-Za-z_]\w*\*$/, '/*');
    if (/[:()?+]/.test(pattern) || pattern.indexOf('*') !== pattern.lastIndexOf('*')) {
        throw new Error(`next.config headers(): cannot translate "${source}" to _headers`);
    }
    return pattern;
}

async function main() {
    if (!existsSync(ASSETS)) throw new Error('.open-next/assets is missing: run `opennextjs-cloudflare build` first.');
    const config = await loadNextConfig(PHASE_PRODUCTION_SERVER);

    const rules: HeaderRule[] = (await config.headers?.()) ?? [];
    const blocks = rules.map((rule) => {
        if (rule.has || rule.missing) throw new Error(`next.config headers(): "${rule.source}" uses has/missing`);
        const params = rule.source.match(/:[A-Za-z_]\w*/g) ?? [];
        for (const { value } of rule.headers) {
            if (params.some((p) => value.includes(p))) throw new Error(`next.config headers(): "${rule.source}" uses a param in a value`);
        }
        return { source: toAssetPattern(rule.source), headers: rule.headers };
    });

    for (const redirect of (await config.redirects?.()) ?? []) {
        if (redirect.source.includes(':')) continue;
        const file = path.join(ASSETS, redirect.source);
        if ([file, `${file}.html`, path.join(file, 'index.html')].some((f) => existsSync(f))) {
            throw new Error(`Redirect source "${redirect.source}" is a static file on Workers; the redirect would never run.`);
        }
    }

    const lines = ['# Generated by scripts/cloudflare-headers.ts from next.config headers(); do not edit.'];
    for (const block of [...blocks, NEXT_STATIC]) {
        lines.push(block.source, ...block.headers.map(({ key, value }) => `  ${key}: ${value}`), '');
    }
    await writeFile(path.join(ASSETS, '_headers'), lines.join('\n'));
    console.log(`.open-next/assets/_headers: ${blocks.length + 1} rules`);
}

main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
});
